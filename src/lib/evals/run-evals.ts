import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { createOpenRouter } from "@openrouter/ai-sdk-provider";
import { analyzeCompany } from "@/lib/firmascope/agent";
import {
  createOpenRouterObjectGenerator,
  LlmBriefGenerator,
  RecordedBriefGenerator,
} from "@/lib/firmascope/generator";
import type { BriefGenerator } from "@/lib/firmascope/generator";
import { FixtureRegistryClient } from "@/lib/firmascope/registry";
import { loadEnvLocal } from "@/lib/env-local";
import { GOLDEN_CASES } from "./golden-cases";
import { scoreBrief } from "./score";
import type { CaseScore, MetricResults } from "./score";

const METRIC_COLUMNS: { key: keyof MetricResults; label: string }[] = [
  { key: "schema_valid", label: "schema_valid" },
  { key: "all_factual_claims_cited", label: "claims_cited" },
  { key: "unknowns_present_when_data_missing", label: "unknowns_ok" },
  { key: "disclaimer_present", label: "disclaimer" },
  { key: "no_forbidden_advice_language", label: "wording_ok" },
  { key: "verdict_reasonable", label: "verdict_ok" },
];

function mark(value: boolean): string {
  return value ? "PASS" : "FAIL";
}

function buildLiveGenerator(): BriefGenerator {
  const apiKey = process.env.OPENROUTER_API_KEY;
  const model = process.env.OPENROUTER_MODEL;
  if (!apiKey || !model) {
    throw new Error("EVAL_LIVE=1 requires OPENROUTER_API_KEY and OPENROUTER_MODEL (.env.local).");
  }
  const openrouter = createOpenRouter({ apiKey });
  return new LlmBriefGenerator(createOpenRouterObjectGenerator(openrouter.chat(model)));
}

function printTable(scores: CaseScore[], mode: string): void {
  console.log(`\nFirmaScope eval run (${mode} mode)\n`);
  console.table(
    scores.map((score) => {
      const row: Record<string, string> = { case: score.id };
      for (const column of METRIC_COLUMNS) {
        row[column.label] = mark(score.metrics[column.key]);
      }
      row.result = score.pass ? "PASS" : "FAIL";
      return row;
    }),
  );
  const passed = scores.filter((score) => score.pass).length;
  console.log(`\n${passed}/${scores.length} cases passed.\n`);
}

function buildMarkdownReport(scores: CaseScore[], mode: string): string {
  const passed = scores.filter((score) => score.pass).length;
  const header = `| Case | Description | ${METRIC_COLUMNS.map((c) => c.label).join(" | ")} | Result |`;
  const divider = `| --- | --- | ${METRIC_COLUMNS.map(() => "---").join(" | ")} | --- |`;
  const rows = scores.map((score) => {
    const cells = METRIC_COLUMNS.map((column) => mark(score.metrics[column.key]));
    return `| \`${score.id}\` | ${score.description} | ${cells.join(" | ")} | ${score.pass ? "PASS" : "FAIL"} |`;
  });

  return [
    "# FirmaScope eval results",
    "",
    `Generated by \`npm run eval\` (${mode} mode) on ${new Date().toISOString()}.`,
    "",
    `**${passed}/${scores.length} golden cases passed.**`,
    "",
    header,
    divider,
    ...rows,
    "",
  ].join("\n");
}

async function main() {
  const live = process.env.EVAL_LIVE === "1";
  loadEnvLocal();

  // Registry data always comes from fixtures — evals must be CI-safe and
  // must not make live registry calls. Only the brief generator switches.
  const registryClient = new FixtureRegistryClient();
  const briefGenerator: BriefGenerator = live ? buildLiveGenerator() : new RecordedBriefGenerator();
  const mode = live ? "live LLM" : "fixture+recorded";

  const scores: CaseScore[] = [];
  for (const goldenCase of GOLDEN_CASES) {
    const result = await analyzeCompany(goldenCase.nip, { registryClient, briefGenerator });
    scores.push(scoreBrief(goldenCase, result.brief));
  }

  printTable(scores, mode);

  const docsDir = path.join(process.cwd(), "docs");
  mkdirSync(docsDir, { recursive: true });
  writeFileSync(path.join(docsDir, "eval-results.md"), buildMarkdownReport(scores, mode));

  if (!scores.every((score) => score.pass)) {
    process.exitCode = 1;
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
